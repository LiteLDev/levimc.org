export const STRINGS: Record<Locale, Strings> = { en, "zh-CN": zhCN, "zh-HK": zhHK };

export interface LocaleValue {
  locale: Locale;
  t: Strings;
}

export const LocaleContext = createContext<LocaleValue>({ locale: "en", t: en });

/** The interface language and its strings. */
export function useI18n(): LocaleValue {
  return useContext(LocaleContext);
}

/** "1,694" in the interface language. */
export function formatNumber(n: number, locale: Locale): string {
  return n.toLocaleString(locale === "en" ? "en-US" : locale);
}

/** "1.7K" / "1.7千" in the interface language. */
export function formatCompact(n: number, locale: Locale): string {
  return new Intl.NumberFormat(locale === "en" ? "en-US" : locale, {
    notation: "compact",
    maximumFractionDigits: 1,
  }).format(n);
}
