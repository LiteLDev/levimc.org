#!/usr/bin/env node
// Adds the legacy documentation redirects to the built site (dist/, after `npm run build`): what
// LiteLDev/liteldev.github.io served under docs.levimc.org before the project docs moved to levimc.org/<Repo>/.
// Its sources are levimc-kit's static pages (kit/static) and the redirect table in legacy/redirects.mjs.
//
//   node legacy/build.mjs dist
//
// Output (in <dist>):
//   404.html                 the site's own 404 (prerendered), with the forwarding map inserted before anything else
//                            (legacy URLs, wrongly cased project paths)
//   <old site>/…             one redirect page per legacy URL, plus the old site's verbatim files
//                            (legacy/redirects.mjs, legacy/files/<old site>/)
//   _kit/…                   the kit assets these pages reference (kit.css, kit.js, kit-nojs-dark.css, sprites)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { uiStrings } from '../kit/components/i18n.ts';
import { KIT_GENERATOR } from '../kit/components/version.ts';
import { MOVED_SITES, ORIGIN, PROJECT_SITES } from './redirects.mjs';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const KIT_STATIC = join(repo, 'kit', 'static');
const LEGACY_FILES = join(repo, 'legacy', 'files');
/** Where the pages load kit assets from (dist/_kit/ → https://levimc.org/_kit/). */
export const ASSET_BASE = '/_kit/';
/** kit/static/kit-nojs-dark.css: the kit's dark theme, loaded only without JavaScript in a dark system theme. */
export const NOJS_DARK_CSS = 'kit-nojs-dark.css';
const KIT_TEMPLATE_BASE = '/levimc-kit/';
const BANNER = '<!-- generated by legacy/build.mjs from kit/static -->';

// ------------------------------------------------------------------------------------------------ routing
// These functions are also inlined into the generated pages (Function#toString, whitespace collapsed), so
// they stay ES5 and contain no comments.

/** Normalises the part of an old URL below the old site root to a page key ("zh-CN/api/hook.html" → "zh-cn/api/hook"). */
export function legacyKey(rest) {
  return rest
    .toLowerCase()
    .replace(/\/+$/, '')
    .replace(/(^|\/)index(\.html)?$/, '')
    .replace(/\.html$/, '')
    .replace(/\/+$/, '')
    .replace(/^\/+/, '');
}

/**
 * The #anchor to append to a forwarded URL: 0 drops it, 1 keeps it, an object { oldId: newId } renames the
 * old heading ids it lists and keeps any other.
 * @param {string} hash location.hash ("" or "#…", percent-encoded)
 * @param {0 | 1 | Record<string, string>} mode
 */
export function legacyHash(hash, mode) {
  if (!mode || !hash) return '';
  if (mode === 1) return hash;
  var id = hash.slice(1);
  try {
    id = decodeURIComponent(id);
  } catch (e) {
    id = hash.slice(1);
  }
  return Object.prototype.hasOwnProperty.call(mode, id) ? '#' + mode[id] : hash;
}

/**
 * Where dist/404.html forwards a request, or null to show the 404 page: old URLs of a moved site go to the
 * new page (or the locale home); wrongly cased project paths (/levilamina/x) go to the project
 * (/LeviLamina/x), because project sites are case-sensitive on GitHub Pages.
 * @param {string} pathname location.pathname (percent-encoded)
 * @param {string} search location.search
 * @param {string} hash location.hash
 * @param {{ o: string, m: { f: string, t: string, p: Record<string, [string, 0 | 1 | Record<string, string>]>, d: [string, string][] }[], c: string[] }} D
 */
export function legacyForward(pathname, search, hash, D) {
  var path = pathname;
  try {
    path = decodeURIComponent(pathname);
  } catch (e) {
    path = pathname;
  }
  var lower = path.toLowerCase();
  for (var i = 0; i < D.m.length; i++) {
    var site = D.m[i];
    if (lower !== site.f.slice(0, -1) && lower.indexOf(site.f) !== 0) continue;
    var key = legacyKey(lower.slice(site.f.length));
    if (Object.prototype.hasOwnProperty.call(site.p, key)) return D.o + site.t + site.p[key][0] + legacyHash(hash, site.p[key][1]);
    for (var j = 0; j < site.d.length; j++) {
      var prefix = site.d[j][0];
      if (!prefix || key === prefix || key.indexOf(prefix + '/') === 0) return D.o + site.t + site.d[j][1];
    }
  }
  var parts = pathname.split('/');
  var first = path.split('/')[1] || '';
  for (var k = 0; k < D.c.length; k++) {
    var name = D.c[k];
    if (first !== name && first.toLowerCase() === name.toLowerCase()) return D.o + '/' + name + '/' + parts.slice(2).join('/') + search + hash;
  }
  return null;
}

/** A page's `hash` setting (legacy/redirects.mjs) as legacyHash() reads it. */
export function hashMode(hash) {
  if (hash === true) return 1;
  if (!hash) return 0;
  const renames = {};
  for (const [to, olds] of Object.entries(hash)) {
    for (const old of olds) {
      if (Object.hasOwn(renames, old)) throw new Error(`old anchor #${old} is mapped twice`);
      renames[old] = to;
    }
  }
  return renames;
}

/** The compact table legacyForward() reads. */
export function forwardTable() {
  return {
    o: ORIGIN,
    m: MOVED_SITES.map((s) => {
      const p = {};
      for (const [from, to, , , hash] of s.pages) p[legacyKey(from)] = [to, hashMode(hash)];
      for (const [from, to] of s.aliases ?? []) if (!Object.hasOwn(p, legacyKey(from))) p[legacyKey(from)] = [to, 0];
      return { f: s.from.toLowerCase(), t: s.to, p, d: (s.fallbacks ?? [['', '']]).map(([from, to]) => [legacyKey(from), to]) };
    }),
    c: PROJECT_SITES,
  };
}

/** Old page key → the file GitHub Pages serves for it ("" → index.html, "api/" → api/index.html, "api/hook" → api/hook.html). */
export function stubFile(siteFrom, page) {
  const dir = siteFrom.replace(/^\/|\/$/g, '');
  if (page === '' || page.endsWith('/')) return `${dir}/${page}index.html`;
  return `${dir}/${page}.html`;
}

// ------------------------------------------------------------------------------------------------ pages
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const scriptJson = (v) => JSON.stringify(v).replace(/</g, "\\u003c");
/** Function source on one line (the inlined functions have no comments and no ASI-sensitive line breaks). */
const inline = (fn) => fn.toString().replace(/\n\s*/g, ' ');
const kitFiles = new Map();
/** A kit/static text file (cached: every redirect page reuses the same snippets). */
const read = (rel) => {
  if (!kitFiles.has(rel)) kitFiles.set(rel, readFileSync(join(KIT_STATIC, rel), 'utf8'));
  return kitFiles.get(rel);
};
/** Drop the "generated by build-static.mjs" banner line of a kit snippet. */
const snippet = (rel) => read(rel).replace(/^<!--[^\n]*-->\n/, '').trim();

/** The kit GlobalBar of a docs page (the Projects tab current, optionally a project in it) in a UI locale. */
export function globalBar(locale, currentProject) {
  let html = snippet(`i18n/globalbar.${locale}.html`);
  // Same attributes GlobalBar.tsx renders with currentProject (aria-current="page"): the Projects tab in the bar
  // and in its phone menu, and the project's row in both Projects lists.
  html = html.replace('<summary class="kit-gbar-link">', '<summary class="kit-gbar-link" aria-current="page">');
  html = html.replace('<summary class="kit-gbar-more-link">', '<summary class="kit-gbar-more-link" aria-current="page">');
  if (currentProject) {
    // the project's docs, in the bar's language since kit 2.22.2 (…/LeviLauncher/zh-Hans/)
    const item = new RegExp(`<a class="kit-proj-main" href="(${ORIGIN}/${currentProject}/(?:[A-Za-z]{2}(?:-[A-Za-z]{2,4})?/)?)">`, 'g');
    html = html.replace(item, '<a class="kit-proj-main" href="$1" aria-current="page">');
  }
  return html;
}

const footer = (locale) => snippet(`i18n/footer.${locale}.html`);

/** A kit sprite from kit/static/icons as inline SVG (inherits currentColor, like the React PixelIcon). */
function inlineIcon(name) {
  return read(`icons/${name}.svg`)
    .trim()
    .replace(' xmlns="http://www.w3.org/2000/svg"', '')
    .replace(/<title>[^<]*<\/title>/, '')
    .replace(/^<svg\b([^>]*)>/, '<svg$1 focusable="false" class="kit-pixel-icon" aria-hidden="true">');
}

/** Replace exactly one occurrence (a kit template that changed shape fails loudly instead of drifting). */
function replaceOnce(html, from, to, what) {
  const n = typeof from === 'string' ? html.split(from).length - 1 : (html.match(new RegExp(from.source, 'g')) ?? []).length;
  if (n !== 1) throw new Error(`a kit/static/pages template changed shape: expected one ${what}, found ${n}`);
  return html.replace(from, () => to);
}

/** A kit page template with its assets under ASSET_BASE; the generator meta names this kit (it lives in this repository). */
const kitTemplate = (name) =>
  read(`pages/${name}`)
    .split(KIT_TEMPLATE_BASE)
    .join(ASSET_BASE)
    .replace(/<meta name="generator" content="levimc-kit [^"]*">/, () => `<meta name="generator" content="${KIT_GENERATOR}">`);

/** Put redirect tags right after <meta charset>, before any stylesheet, so the redirect is instant. */
function hoistIntoHead(html, tags) {
  const charset = '<meta charset="utf-8">';
  if (!html.includes(charset)) throw new Error('template without <meta charset="utf-8">');
  return html.replace(charset, () => [charset, BANNER, ...tags].join('\n  '));
}

/** The kit's skip link in the page's language (kit.js re-translates it when the visitor prefers another one). */
function skipLink(html, lang) {
  const en = `<a class="kit-skip-link" href="#kit-main" data-kit-t="skipToContent">${esc(uiStrings('en').skipToContent)}</a>`;
  return replaceOnce(html, en, en.replace(/>[^<]*<\/a>$/, `>${esc(uiStrings(lang).skipToContent)}</a>`), 'skip link');
}

/** The forwarding map that runs first on the 404 page: forwards legacy URLs and wrongly cased project paths. */
export function forwardScript() {
  return (
    `<script>(function(){${inline(legacyKey)}${inline(legacyHash)}${inline(legacyForward)}` +
    `try{var u=legacyForward(location.pathname,location.search,location.hash,${scriptJson(forwardTable())});` +
    `if(u&&u!==location.href){var d=document.documentElement;d.style.visibility="hidden";` +
    `setTimeout(function(){d.style.visibility=""},3000);location.replace(u)}}catch(e){}})();</script>`
  );
}

/** The site's 404 page with the forwarding map right after <meta charset>, before any stylesheet or script. */
export function patchNotFound(html) {
  if (html.includes('function legacyForward')) throw new Error('404.html already has the forwarding map');
  const charset = /<meta charset="utf-8"\s*\/?>/i.exec(html);
  if (!charset) throw new Error('404.html without <meta charset="utf-8">');
  return html.replace(charset[0], () => `${charset[0]}
    ${forwardScript()}`);
}

// Text of the redirect pages (visible only without JavaScript or for the moment before the redirect).
// Same structure as the kit's root redirect page: the heading links the target.
const STUB_TEXT = {
  en: {
    title: (page) => `Moved: ${page} - LeviMC Docs`,
    eyebrow: 'Page moved',
    heading: (link) => `Redirecting to ${link}…`,
    text: (s) => `The ${s.oldName} docs are now part of the ${s.newName} documentation.`,
    button: 'Continue',
  },
  'zh-CN': {
    title: (page) => `已迁移：${page} - LeviMC Docs`,
    eyebrow: 'Page moved',
    heading: (link) => `正在跳转到 ${link}…`,
    text: (s) => `${s.oldName} 文档已并入 ${s.newName} 文档。`,
    button: '继续',
  },
  'zh-HK': {
    title: (page) => `已遷移：${page} - LeviMC Docs`,
    eyebrow: 'Page moved',
    heading: (link) => `正在跳轉到 ${link}…`,
    text: (s) => `${s.oldName} 文檔已併入 ${s.newName} 文檔。`,
    button: '繼續',
  },
};

/** The redirect script of a stub page: the target plus the old #anchor as `hash` says. */
function stubRedirect(url, hash) {
  const mode = hashMode(hash);
  if (mode === 0) return `<script>location.replace(${scriptJson(url)});</script>`;
  if (mode === 1) return `<script>location.replace(${scriptJson(url)}+location.hash);</script>`;
  return `<script>(function(){${inline(legacyHash)}location.replace(${scriptJson(url)}+legacyHash(location.hash,${scriptJson(mode)}))})();</script>`;
}

/**
 * A redirect page: the kit's static 404 page (same head, backdrop and shell) with the GlobalBar and footer in
 * the page's language, a "Redirecting to …" card instead of the project grid, and the redirect tags first.
 */
function stubPage(site, [, to, lang, pageTitle, hash], notFound) {
  const url = ORIGIN + site.to + to;
  const t = STUB_TEXT[lang];
  if (!t) throw new Error(`no stub text for ${lang}`);
  const link = `<a href="${esc(url)}">${esc(pageTitle)}</a>`;
  const main = `<main id="kit-main" class="kit-static-main">
    <section class="kit-static-card px-card kit-painted">
      <div class="kit-notfound-compass kit-slot" aria-hidden="true"><img src="${ASSET_BASE}icons/pickaxe.svg" width="64" height="64" alt="" class="pixelated"></div>
      <p class="kit-pixel-label kit-static-eyebrow">${esc(t.eyebrow)}</p>
      <h1 class="kit-static-title">${t.heading(link)}</h1>
      <p class="kit-static-text">${esc(t.text(site))}</p>
      <p class="kit-static-actions"><a class="mc-btn mc-btn-primary" href="${esc(url)}">${esc(t.button)}${inlineIcon('arrow-right')}</a></p>
    </section>
  </main>`;
  let html = notFound;
  html = replaceOnce(html, '<html lang="en">', `<html lang="${esc(lang)}">`, '<html lang="en">');
  html = replaceOnce(html, /<title>[^<]*<\/title>/, `<title>${esc(t.title(pageTitle))}</title>`, '<title>');
  html = replaceOnce(html, /\n\s*<meta name="robots" content="noindex">/, '', 'robots meta');
  html = replaceOnce(html, globalBar('en'), globalBar(lang, site.to.replace(/\//g, '')), 'GlobalBar');
  html = replaceOnce(html, footer('en'), footer(lang), 'footer');
  html = replaceOnce(html, /<main id="kit-main"[^>]*>[\s\S]*?<\/main>/, main, '<main>');
  return hoistIntoHead(skipLink(html, lang), [
    `<link rel="canonical" href="${esc(url)}">`,
    `<meta http-equiv="refresh" content="0; url=${esc(url)}">`,
    stubRedirect(url, hash),
  ]);
}

/** Every redirect page of a moved site: [old page, new page, lang, title, hash] for its pages and directory aliases. */
export function stubEntries(site) {
  const entries = [...site.pages];
  for (const [from, to] of site.aliases ?? []) {
    if (!from.endsWith('/')) continue; // a file alias: only the 404 forwards it
    const page = site.pages.find((p) => p[1] === to);
    if (!page) throw new Error(`alias ${site.from}${from} → ${to}: no page with that target`);
    entries.push([from, to, page[2], page[3], false]);
  }
  return entries;
}

// ------------------------------------------------------------------------------------------------ build
/** Every file the generator adds, as dist-relative path → contents (404.html is patched separately). */
export function generate() {
  const files = new Map();
  const add = (rel, body) => {
    if (files.has(rel)) throw new Error(`two sources for ${rel}`);
    files.set(rel, body);
  };
  const notFound = kitTemplate('404.html');
  for (const site of MOVED_SITES) {
    if (!/^\/[A-Za-z0-9._-]+\/$/.test(site.from) || /^\/(_kit|\.+)\/$/.test(site.from)) throw new Error(`MOVED_SITES.from must be one path segment like "/old-site/": ${site.from}`);
    for (const entry of stubEntries(site)) add(stubFile(site.from, entry[0]), stubPage(site, entry, notFound));
    const dir = site.from.slice(1, -1);
    for (const rel of site.files ?? []) add(`${dir}/${rel}`, readFileSync(join(LEGACY_FILES, dir, rel)));
  }
  // Copy exactly the kit assets the pages reference.
  const assets = new Set();
  for (const [rel, body] of files) if (rel.endsWith('.html')) for (const m of body.matchAll(/["'(]\/_kit\/([^"')\s?#]+)/g)) assets.add(m[1]);
  for (const rel of [...assets].sort()) if (!files.has(`_kit/${rel}`)) add(`_kit/${rel}`, readFileSync(join(KIT_STATIC, rel)));
  return files;
}

function main() {
  const outArg = process.argv[2];
  if (!outArg || outArg.startsWith('--')) {
    console.error('Usage: node legacy/build.mjs <dist>');
    process.exit(2);
  }
  const out = resolve(outArg);
  const notFound = join(out, '404.html');
  if (!existsSync(notFound)) throw new Error(`${notFound} is missing: run the site build first`);
  const files = generate();
  // The site build owns everything else: a legacy path that it publishes too is a conflict, not an overwrite.
  for (const rel of files.keys()) if (existsSync(join(out, rel))) throw new Error(`${join(out, rel)} exists already: a legacy path collides with the site`);
  for (const [rel, body] of files) {
    mkdirSync(dirname(join(out, rel)), { recursive: true });
    writeFileSync(join(out, rel), body);
  }
  writeFileSync(notFound, patchNotFound(readFileSync(notFound, 'utf8')));
  console.log(`legacy: wrote ${files.size} files and the 404 forwarding map to ${relative(process.cwd(), out) || out}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
