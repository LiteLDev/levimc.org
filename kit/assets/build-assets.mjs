// Pixel dissolve masks: the one way a painting meets the plain canvas anywhere in the kit. Its edge breaks up into
// 6px blocks whose density ramps from none to solid over 16 cells (96px), with a slow wobble along the edge so it
// reads as brushwork rather than a uniform dither. 48 cells along the edge (tiles seamlessly: cells are independent).
// Black = keep. `to` names the solid side: 'bottom' (a painting below the edge rises into the page: footer),
// 'top' (a painting above dissolves downwards: hero, docs band), 'right' (a painting on the right dissolves leftwards).
function dissolveMask(seed, to) {
  const r = mulberry32(seed);
  const L = 48;
  const D = 16;
  const waves = [1, 2, 3, 5, 8].map((f) => ({ f, ph: r() * Math.PI * 2, a: 1 / Math.sqrt(f) }));
  const amp = waves.reduce((sum, w) => sum + w.a, 0);
  const cells = [];
  for (let i = 0; i < L; i++) {
    const wobble = (waves.reduce((sum, w) => sum + w.a * Math.sin((i / L) * Math.PI * 2 * w.f + w.ph), 0) / amp) * 0.42;
    for (let k = 0; k < D; k++) {
      const t = ((k + 0.5) / D) * 1.15 + wobble; // 0 at the open side, ≥ 1 (solid) over the last cells
      const p = Math.min(1, Math.max(0, t)) ** 1.35;
      if (r() >= p) continue;
      const depth = to === 'top' ? D - 1 - k : k; // row/column index from the top/left of the tile
      const [x, y] = to === 'right' ? [k, i] : [i, depth];
      cells.push(`M${x} ${y}h1v1h-1z`);
    }
  }
  const [w, h] = to === 'right' ? [D, L] : [L, D];
  return `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${w} ${h}' preserveAspectRatio='none' shape-rendering='crispEdges'><path d='${cells.join('')}'/></svg>`;
}
